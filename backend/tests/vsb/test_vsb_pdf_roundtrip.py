"""PDF round trip through PyMuPDF (the project's real PDF reader) - coordinate seat mapping.

The PDFs here are GENERATED by this test from the real 20-Nov-2026 AN text (hall sheet pages), laid out as a 4x7 serpentine grid.
They are NOT VSB's binary files (the build sandbox could not download them), so cell geometry is an approximation of TCPDF's.
What this proves: with real word boxes, every register number is mapped to the seat label in its own row and column, an empty
cell never shifts a neighbour, and the parser output equals the independent reference.
"""
import re
from datetime import date

import pytest

fitz = pytest.importorskip("fitz")
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

from app.vsb_alloc import pdfwords
from app.vsb_alloc.hall_parser import parse_hall_pdf
from app.vsb_alloc.reconcile import reconcile
from app.vsb_alloc.seat_parser import parse_seat_pdf
from vsb import independent_compare as IC

COLX = [40, 170, 300, 430]


def _seat_pdf(path, shuffle_stream=False):
    c = canvas.Canvas(str(path), pagesize=A4)
    W, H = A4
    for text in IC.pages("20.11.26-AN-SEAT.pages.txt"):
        lines = [l for l in text.splitlines() if l.strip()]
        h_i = next(i for i, l in enumerate(lines) if l.startswith("EXAM HALL"))
        t_i = next(i for i, l in enumerate(lines) if l.startswith("CODE TITLE"))
        y = H - 40
        c.setFont("Helvetica", 8)
        for l in lines[:h_i + 1]:
            c.drawString(40, y, l); y -= 12
        grid = []
        for row_no, ln in enumerate(lines[h_i + 1:t_i]):
            toks = ln.split()
            cells, k = [], 0
            while k < len(toks):                      # (seat, reg|None) in printed order => 4 columns
                reg = toks[k + 1] if k + 1 < len(toks) and len(toks[k + 1]) == 12 else None
                cells.append((toks[k], reg)); k += 2 if reg else 1
            assert len(cells) == 4
            grid.append(cells)
        y -= 6
        order = [(r, ci) for r in range(len(grid)) for ci in range(4)]
        if shuffle_stream:                           # content-stream order differs from reading order (text-order variation)
            order = order[::-1]
        for r, ci in order:
            seat, reg = grid[r][ci]
            yy = y - r * 14
            c.drawString(COLX[ci], yy, seat)
            if reg:
                c.drawString(COLX[ci] + 22, yy, reg)
        y -= 7 * 14 + 10
        for l in lines[t_i:]:
            c.drawString(40, y, l[:150]); y -= 12
        c.showPage()
    c.save()


@pytest.fixture(scope="module")
def ref():
    return IC.report()


@pytest.mark.parametrize("shuffle", [False, True])
def test_coordinate_seat_mapping_equals_reference(tmp_path, ref, shuffle):
    p = tmp_path / "seat.pdf"
    _seat_pdf(p, shuffle)
    pages = pdfwords.read_pages(str(p))
    assert len(pages) == 16 and all(pg.words for pg in pages)
    doc = parse_seat_pdf(pages)
    assert {s.layout for s in doc.sheets} == {"coordinates"}
    got = {a.register_number: (s.hall, a.seat) for s in doc.sheets for a in s.assignments}
    assert got == ref["assignments"] and len(got) == 390
    assert all(not a.flags for s in doc.sheets for a in s.assignments)
    assert [i for i in doc.all_issues() if i.severity == "error"] == []
    # empty cells never produce a seat: A104 has 13 empty labelled seats and exactly 15 occupied
    a104 = next(s for s in doc.sheets if s.hall == "MB III A104")
    assert a104.grid_count == 15 and 28 in a104.empty_seats and 19 in a104.empty_seats


def test_coordinate_path_makes_records_unflagged_for_seat_source(tmp_path, ref):
    sp = tmp_path / "seat.pdf"
    _seat_pdf(sp)
    seat = parse_seat_pdf(pdfwords.read_pages(str(sp)))
    from app.vsb_alloc.common import PageInput
    hall = parse_hall_pdf([PageInput(i, t) for i, t in enumerate(IC.pages("20.11.26-AN-HALL.pages.txt"))])
    rc = reconcile(hall, seat, date(2026, 11, 20), "AN")
    assert len(rc.records) == 390 and not any(r.blocking for r in rc.records)
    assert not any("seat_from_text_order" in r.flags for r in rc.records)
    assert all(r.seat == ref["assignments"][r.register_number][1] for r in rc.records)
