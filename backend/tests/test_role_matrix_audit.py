"""Automated route x role audit. Calls EVERY registered API route as anonymous, student, invigilator, staff and admin
with placeholder ids and an empty body, and records whether the request was refused (401/403) or reached the handler.
It asserts the invariants that matter and writes the full matrix to docs/ROLE_MATRIX.md for review."""
import re
from pathlib import Path

from conftest import make_student, make_user, login
from app.main import create_app

ROLES = ("anonymous", "student", "invigilator", "staff", "admin")
SKIP = re.compile(r"/(logout|logout-all|change-password|shutdown|restore|reset-database|backup|delete-account)(/|$)|/api/auth/login")
# Routes that anonymous callers are deliberately allowed to reach (reviewed in docs/ROLE_MATRIX.md).
PUBLIC_OK = re.compile(
    r"^(/api/(health|ready|version|config|exams|halls|announcements|vsb/official-links|auth/(login|refresh|forgot|reset|register|activate)\S*"
    r"|portal/\S*|public/\S*|students/\{register_number\}|lookup/\{register_number\}|allotments/\{register_number\})"
    r"|/(docs|redoc|openapi\.json)|/?)$")
# Reviewed in docs/ROLE_MATRIX.md: public lookups are rate-limited (public_guard), return register/department/year only (no names),
# and list only published/verified data; results require sign-in.
# Self-service routes any signed-in user (student included) may legitimately write to.
SELF_WRITE = re.compile(r"^/api/(auth/\S*|me/\S*|notifications(/\S*)?|vsb-allocation/my\S*)$")


def _fill(path):
    path = path.replace("{register_number}", "999117582001")      # a well-formed number, so auth (not validation) is what answers
    return re.sub(r"\{[^}]+\}", "1", path)


def _matrix(client, heads):
    rows = []
    for path, ops in create_app().openapi()["paths"].items():
        for m in sorted(x.upper() for x in ops if x.upper() in ("GET", "POST", "PUT", "PATCH", "DELETE")):
            url = _fill(path)
            if SKIP.search(url):
                continue
            res = {}
            for role in ROLES:
                kw = {"headers": heads.get(role, {})}
                if m in ("POST", "PUT", "PATCH", "DELETE"):
                    kw["json"] = {}
                res[role] = client.request(m, url, **kw).status_code
            rows.append((m, path, res))
    return rows


def test_role_matrix_invariants(client, db):
    for u, role in (("aud_student", "student"), ("aud_invig", "invigilator"), ("aud_staff", "staff"), ("aud_admin", "admin")):
        make_user(db, u, role, student=make_student(db, "999117582001", "Audit Student", "ECE", 2) if role == "student" else None)
    heads = {"student": login(client, "aud_student"), "invigilator": login(client, "aud_invig"),
             "staff": login(client, "aud_staff"), "admin": login(client, "aud_admin")}
    rows = _matrix(client, heads)
    assert len(rows) > 100
    denied = lambda s: s in (401, 403)
    problems = []
    for m, path, res in rows:
        if not denied(res["anonymous"]) and not PUBLIC_OK.match(path):
            problems.append(f"ANON reaches {m} {path} -> {res['anonymous']}")
        if m != "GET":
            for role in ("student", "invigilator"):
                if not denied(res[role]) and not SELF_WRITE.match(path) and not PUBLIC_OK.match(path):
                    problems.append(f"{role.upper()} can write {m} {path} -> {res[role]}")
        # Admin-only by design: user management and the VSB allocation publish/withdraw/resolve actions.
        # (Exam publish is intentionally open to staff - department-scoped - per the existing role design.)
        if path.startswith("/api/admin/users") or (path.startswith("/api/vsb-allocation") and any(
                k in path for k in ("resolve-conflict", "publish", "withdraw")) and not path.endswith("/preview")):
            if not denied(res["staff"]) and "/users/me" not in path:
                problems.append(f"STAFF reaches admin-only {m} {path} -> {res['staff']}")
    lines = ["# Role x route matrix (generated by tests/test_role_matrix_audit.py)", "",
             "Cell = HTTP status for an empty request. 401/403 = refused by the backend; anything else = reached the handler "
             "(404/422 mean the handler ran and rejected the placeholder id/body).", "",
             "| Method | Path | " + " | ".join(ROLES) + " |", "|---|---|" + "---|" * len(ROLES)]
    lines += [f"| {m} | `{p}` | " + " | ".join(str(res[r]) for r in ROLES) + " |" for m, p, res in sorted(rows, key=lambda x: (x[1], x[0]))]
    Path(__file__).resolve().parents[2].joinpath("docs", "ROLE_MATRIX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    assert not problems, "\n".join(problems)
